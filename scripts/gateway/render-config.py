"""Render provider configs from the reviewed route contract; --check detects drift."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
ROUTES = json.loads((ROOT / "deploy/gateway/routes.json").read_text())

def match(route):
    path = route["path"]
    if route["match"] == "Exact":
        return f"Path(`{path}`)"
    return f"(Path(`{path}`) || PathPrefix(`{path}/`))"

def dynamic():
    lines = ['# Generated by scripts/gateway/render-config.py; edit deploy/gateway/routes.json.',
             '{{ $tls := ne (env "CLINICFLOW_GATEWAY_TLS") "false" }}', 'http:', '  routers:']
    for route in ROUTES:
        for visibility in ("public", "internal"):
            name = f'{visibility}-{route["id"]}'
            rule = match(route)
            if visibility == "public":
                rule = f'Host(`api.clinicflow.localhost`) && {rule}'
            lines += [f'    {name}:', f'      rule: "{rule}"',
                      '      entryPoints: ' + ('[api]' if visibility == 'internal' else '[{{ if $tls }}websecure{{ else }}web{{ end }}]'),
                      f'      service: {route["backend"]}',
                      '      middlewares: [' + ('headers' if visibility == 'internal' else '{{ if $tls }}secure-headers{{ else }}headers{{ end }}') + f', {route["id"]}-rewrite, ' + ('internal-limit]' if visibility == 'internal' else f'{route["policy"]}-limit]')]
            if visibility == 'public':
                lines += ['{{ if $tls }}', '      tls: {}', '{{ end }}']
    lines += ['    ui:', '      rule: "Host(`clinicflow.localhost`){{ if not $tls }} || Host(`127.0.0.1`) || Host(`host.docker.internal`) || Host(`localhost`){{ end }}"',
              '      entryPoints: [{{ if $tls }}websecure{{ else }}web{{ end }}]', '      service: frontend',
              # The catch-all's default priority is its rule length, which reaches the BFF routes' priorities over HTTP.
              '      priority: 1',
              '      middlewares: [{{ if $tls }}secure-headers{{ else }}headers{{ end }}]', '{{ if $tls }}', '      tls: {}', '{{ end }}']
    for name, path, policy in [('bff-api','/api','public'),('bff-login','/api/auth/login','auth'),('bff-register','/api/auth/register','auth')]:
        route_match = f'Path(`{path}`)' if policy == 'auth' else '(Path(`/api`) || PathPrefix(`/api/`))'
        lines += [f'    {name}:', f'      rule: "(Host(`clinicflow.localhost`){{{{ if not $tls }}}} || Host(`127.0.0.1`) || Host(`host.docker.internal`) || Host(`localhost`){{{{ end }}}}) && {route_match}"',
                  '      entryPoints: [{{ if $tls }}websecure{{ else }}web{{ end }}]', '      service: frontend',
                  f'      priority: {100 if policy == "auth" else 50}', f'      middlewares: [{{{{ if $tls }}}}secure-headers{{{{ else }}}}headers{{{{ end }}}}, {policy}-limit]',
                  '{{ if $tls }}', '      tls: {}', '{{ end }}']
    lines += ['{{ if $tls }}', '    redirect:', '      rule: "Host(`clinicflow.localhost`) || Host(`api.clinicflow.localhost`)"',
              '      entryPoints: [web]', '      service: noop@internal', '      middlewares: [https-redirect]', '{{ end }}', '  middlewares:']
    for route in ROUTES:
        lines += [f'    {route["id"]}-rewrite:']
        if route['match'] == 'Exact':
            lines += ['      replacePath:', f'        path: {route["upstream"]}']
        else:
            lines += ['      replacePathRegex:', f'        regex: "^{route["path"]}(/.*)?$"', f'        replacement: "{route["upstream"]}${{1}}"']
    lines += ['    headers:', '      headers:', '        contentTypeNosniff: true', '        frameDeny: true', '        referrerPolicy: no-referrer',
              '    secure-headers:', '      headers:', '        contentTypeNosniff: true', '        frameDeny: true', '        referrerPolicy: no-referrer', '        stsSeconds: 86400',
              '    https-redirect:', '      redirectScheme:', '        scheme: https', '        port: "{{ env "CLINICFLOW_GATEWAY_HTTPS_PORT" | default "443" }}"', '        permanent: true']
    for name, average, period, burst in [('public',20,'1s',40),('auth',10,'1m',5),('internal',100,'1s',200)]:
        env = name.upper()
        lines += [f'    {name}-limit:', '      rateLimit:',
                  f'        average: {{{{ env "CLINICFLOW_GATEWAY_{env}_AVERAGE" | default "{average}" }}}}',
                  f'        period: {{{{ env "CLINICFLOW_GATEWAY_{env}_PERIOD" | default "{period}" }}}}',
                  f'        burst: {{{{ env "CLINICFLOW_GATEWAY_{env}_BURST" | default "{burst}" }}}}']
    lines += ['  services:']
    for name, port in sorted({(r['backend'], r['port']) for r in ROUTES} | {('frontend',3000)}):
        lines += [f'    {name}:', '      loadBalancer:', '        servers:', f'          - url: http://{name}:{port}']
    lines += ['{{ if $tls }}', 'tls:', '  certificates:', '    - certFile: /certs/edge.crt', '      keyFile: /certs/edge.key', '  options:', '    default:', '      minVersion: VersionTLS12', '{{ end }}']
    return '\n'.join(lines) + '\n'

parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
outputs = {
    'deploy/gateway/dynamic/routes.yaml': dynamic(),
    'deploy/helm/gateway/routes.json': json.dumps(ROUTES, indent=2) + '\n',
}
for path, content in outputs.items():
    target = ROOT / path
    if args.check:
        if not target.exists() or target.read_text() != content:
            raise SystemExit(f'{path} is stale: run scripts/gateway/render-config.py')
    else:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content, encoding='utf-8', newline='\n')
print('Gateway configuration matches route contract.' if args.check else 'Rendered gateway configuration.')
